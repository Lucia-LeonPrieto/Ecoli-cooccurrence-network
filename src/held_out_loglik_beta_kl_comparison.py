#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
held_out_loglik_beta_kl_comparison.py
=======================================
Consolidated, reproducible comparison of held-out ELBO / log-likelihood
(5-fold CV on the real 150-strain matrix) across beta_kl values for the
winning architecture (latent_dim=32, hidden_dim=64), needed to describe in
the manuscript how the composite ground-truth criterion's winner
(beta_kl=0.01) compares to the held-out-log-likelihood criterion's own
winner (beta_kl=0.05), plus the "boundary-optimum" follow-up
(beta_kl in {0.001, 0.005}).

Three of the five beta_kl values (0.01, 0.05, 0.10) were already computed as
part of the 48-config grid in
results/ground_truth_validation/held_out_evaluation.csv (produced by
simulation_ground_truth.py's run_hyperparameter_search_ground_truth()) and
are read from there, NOT recomputed. The other two (0.001, 0.005) were only
ever computed ad hoc, in-terminal, during the boundary-optimum check and
never saved to a reproducible file -- this script recomputes them (same
function, same seed, same k_folds as the original grid) and saves
everything together.

Wired into run_all.py as step 10 (Table S4, cited in Methods 2.4), so a
clean `run_all.py` reproduces this number without a separate manual run.
NOT re-running the full 48-config grid here, by the same reasoning as
run_hyperparameter_search_ground_truth() itself: hyperparameter selection is
a one-time step whose result is already fixed in src/vae_config.json, and
re-running the full grid on every `run_all.py` invocation would add runtime
for no benefit -- the selection does not change. Consequently,
held_out_evaluation.csv (below) is a checked-in input this script reads,
not something run_all.py regenerates from scratch. Run standalone with:
    python src/held_out_loglik_beta_kl_comparison.py

Inputs:
    data/input/EffectorRepertoire_Ecoli.xlsx
    results/ground_truth_validation/held_out_evaluation.csv  (for beta_kl
        0.01/0.05/0.10 -- ships with the repo's results/, produced by the
        one-time hyperparameter grid search, NOT regenerated by run_all.py)
Outputs:
    results/ground_truth_validation/TableS4_detail.csv
        long format: one row per (beta_kl, fold)
    results/ground_truth_validation/TableS4.csv
        one row per beta_kl: mean/std ELBO and log-likelihood across the 5 folds
        (this is the manuscript's Table S4)
"""
import os
import sys
import time
from pathlib import Path

import pandas as pd

SRC_DIR = Path(__file__).resolve().parent
ROOT = SRC_DIR.parent
sys.path.insert(0, str(SRC_DIR))
os.environ.setdefault("MPLBACKEND", "Agg")
os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("MKL_NUM_THREADS", "1")
import torch  # noqa: E402
torch.set_num_threads(1)

from inference_functions import load_binary_matrix, evaluate_vae_held_out_likelihood  # noqa: E402
from vae_config_loader import load_vae_config  # noqa: E402

INPUT_XLSX = ROOT / "data" / "input" / "EffectorRepertoire_Ecoli.xlsx"
GRID_CSV = ROOT / "results" / "ground_truth_validation" / "held_out_evaluation.csv"
OUT_LONG = ROOT / "results" / "ground_truth_validation" / "TableS4_detail.csv"
OUT_SUMMARY = ROOT / "results" / "ground_truth_validation" / "TableS4.csv"

LATENT_DIM, HIDDEN_DIM = 32, 64
BETA_KL_FROM_GRID = [0.01, 0.05, 0.10]          # already in held_out_evaluation.csv
BETA_KL_NEW = [0.001, 0.005]                    # boundary-optimum probes, not in the 48-config grid
K_FOLDS = 5
SEED = 42


def main() -> int:
    t0 = time.time()
    rows = []

    reused_beta_kl = []
    if GRID_CSV.is_file():
        grid_df = pd.read_csv(GRID_CSV)
        sub = grid_df[(grid_df["latent_dim"] == LATENT_DIM) &
                      (grid_df["hidden_dim"] == HIDDEN_DIM) &
                      (grid_df["beta_kl"].isin(BETA_KL_FROM_GRID))]
        for _, r in sub.iterrows():
            rows.append(dict(beta_kl=float(r["beta_kl"]), fold=int(r["fold"]),
                             elbo_held_out=float(r["elbo_held_out"]),
                             log_likelihood_held_out=float(r["log_likelihood_held_out"]),
                             source="held_out_evaluation.csv (48-config grid)"))
        reused_beta_kl = sorted(sub["beta_kl"].unique().tolist())
        print(f"reused {len(sub)} rows from {GRID_CSV.relative_to(ROOT)} "
              f"for beta_kl in {reused_beta_kl}")
    else:
        print(f"WARNING: {GRID_CSV} not found -- beta_kl {BETA_KL_FROM_GRID} will be "
              "recomputed from scratch instead of reused")

    to_compute = BETA_KL_NEW + [b for b in BETA_KL_FROM_GRID if b not in reused_beta_kl]

    if to_compute:
        matrix = load_binary_matrix(INPUT_XLSX)
        cfg = load_vae_config()
        base_params = dict(cfg["base_params"])
        for beta_kl in to_compute:
            vae_params = {**base_params, "latent_dim": LATENT_DIM,
                         "hidden_dim": HIDDEN_DIM, "beta_kl": beta_kl}
            t1 = time.time()
            ho = evaluate_vae_held_out_likelihood(
                matrix, vae_params, k_folds=K_FOLDS, seed=SEED,
                lineage_csv=None, verbose=False,
            )
            for _, r in ho.iterrows():
                rows.append(dict(beta_kl=beta_kl, fold=int(r["fold"]),
                                 elbo_held_out=float(r["elbo_held_out"]),
                                 log_likelihood_held_out=float(r["log_likelihood_held_out"]),
                                 source="computed by this script"))
            print(f"  beta_kl={beta_kl}: done in {time.time() - t1:.1f}s")

    long_df = pd.DataFrame(rows).sort_values(["beta_kl", "fold"])
    long_df.insert(0, "latent_dim", LATENT_DIM)
    long_df.insert(1, "hidden_dim", HIDDEN_DIM)
    OUT_LONG.parent.mkdir(parents=True, exist_ok=True)
    long_df.to_csv(OUT_LONG, index=False)

    summary_df = long_df.groupby(["latent_dim", "hidden_dim", "beta_kl"]).agg(
        mean_elbo_held_out=("elbo_held_out", "mean"),
        std_elbo_held_out=("elbo_held_out", "std"),
        mean_log_likelihood_held_out=("log_likelihood_held_out", "mean"),
        std_log_likelihood_held_out=("log_likelihood_held_out", "std"),
        n_folds=("fold", "count"),
    ).reset_index().sort_values("beta_kl")
    summary_df.to_csv(OUT_SUMMARY, index=False)

    print("\n" + "=" * 78)
    print("  SUMMARY -- held-out log-likelihood / ELBO by beta_kl (latent=32, hidden=64)")
    print("=" * 78)
    print(summary_df.to_string(index=False))

    print(f"\n  -> {OUT_LONG.relative_to(ROOT)}")
    print(f"  -> {OUT_SUMMARY.relative_to(ROOT)}")
    print(f"\n  done in {time.time() - t0:.1f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
